create or replace view public.invoice_balances
with (security_invoker = true) as
select
  i.*,
  coalesce(a.allocated_amount, 0)::numeric(14, 2) as transaction_paid_amount,
  least(i.total_amount,
    least(i.total_amount, i.manual_paid_amount) + coalesce(a.allocated_amount, 0)
  )::numeric(14, 2) as paid_amount,
  greatest(i.total_amount - least(i.total_amount,
    least(i.total_amount, i.manual_paid_amount) + coalesce(a.allocated_amount, 0)
  ), 0)::numeric(14, 2) as balance_due,
  case
    when i.status = 'void' then 'void'
    when i.status = 'draft' then 'draft'
    when greatest(i.total_amount - least(i.total_amount,
      least(i.total_amount, i.manual_paid_amount) + coalesce(a.allocated_amount, 0)
    ), 0) = 0 then 'paid'
    when i.due_date < current_date then 'overdue'
    when least(i.total_amount, i.manual_paid_amount) + coalesce(a.allocated_amount, 0) > 0 then 'partial'
    else 'unpaid'
  end as payment_status
from public.invoices i
left join (
  select invoice_id, sum(allocated_amount)::numeric(14, 2) as allocated_amount
  from public.invoice_payment_allocations
  group by invoice_id
) a on a.invoice_id = i.id;

-- Project profit uses agreed price minus both ordinary costs and accrued payables.
-- Cash profit uses only expense transactions actually paid.
create or replace view public.project_financial_summary
with (security_invoker = true) as
select
  p.id as project_id, p.name as project_name, p.status as project_status, p.final_price as agreed_fee,
  coalesce(inv.invoiced_value, 0)::numeric(14, 2) as invoiced_value,
  (coalesce(tx.income_total, 0) + coalesce(inv.manual_paid_total, 0))::numeric(14, 2) as received_cash,
  coalesce(inv.accounts_receivable, 0)::numeric(14, 2) as accounts_receivable,
  (coalesce(tx.expense_total, 0) + coalesce(ob.obligation_total, 0))::numeric(14, 2) as total_project_expenses,
  (p.final_price - coalesce(tx.expense_total, 0) - coalesce(ob.obligation_total, 0))::numeric(14, 2) as profit,
  (coalesce(tx.income_total, 0) + coalesce(inv.manual_paid_total, 0) - coalesce(tx.cash_expense_total, 0))::numeric(14, 2) as cash_profit,
  case when p.status = 'Completed' and coalesce(inv.invoiced_value, 0) >= p.final_price and coalesce(inv.accounts_receivable, 0) = 0
    then 'Final Project Profit' else 'Current Project Profit' end as profit_label
from public.projects p
left join lateral (
  select sum(i.total_amount) filter (where i.status not in ('draft','void')) as invoiced_value,
    sum(b.balance_due) filter (where b.status not in ('draft','void')) as accounts_receivable,
    sum(least(i.total_amount, i.manual_paid_amount)) filter (where i.status not in ('draft','void')) as manual_paid_total
  from public.invoices i join public.invoice_balances b on b.id=i.id where i.project_id=p.id
) inv on true
left join lateral (
  select sum(t.amount) filter (where t.transaction_type='income') as income_total,
    sum(t.amount) filter (where t.transaction_type='expense' and t.payable_id is null) as expense_total,
    sum(t.amount) filter (where t.transaction_type='expense') as cash_expense_total
  from public.financial_transactions t where t.project_id=p.id
) tx on true
left join lateral (
  select sum(amount_due) as obligation_total from public.project_payables where project_id=p.id
) ob on true;

-- Accrued project profit is distinct from cash flow and includes unpaid payables.
create or replace view public.company_financial_summary
with (security_invoker = true) as
select base.*,
  coalesce((select sum(total_project_expenses) from public.project_financial_summary), 0)::numeric(14, 2)
    + coalesce((select sum(amount) from public.financial_transactions where transaction_type='expense' and project_id is null), 0)::numeric(14, 2)
    as total_accrued_costs,
  coalesce((select sum(profit) from public.project_financial_summary), 0)::numeric(14, 2) as total_project_profit
from (
  select current_date as as_of_date,
    coalesce((select sum(amount) from public.financial_transactions where transaction_type='income'), 0)::numeric(14, 2) as ledger_income,
    coalesce((select sum(amount) from public.financial_transactions where transaction_type='expense'), 0)::numeric(14, 2) as total_expenses,
    coalesce((select sum(least(total_amount, manual_paid_amount)) from public.invoices where status not in ('draft','void')), 0)::numeric(14, 2) as legacy_invoice_paid,
    (coalesce((select sum(amount) from public.financial_transactions where transaction_type='income'), 0)
      + coalesce((select sum(least(total_amount, manual_paid_amount)) from public.invoices where status not in ('draft','void')), 0))::numeric(14, 2) as total_received_cash,
    coalesce((select sum(total_amount) from public.invoices where status not in ('draft','void')), 0)::numeric(14, 2) as total_invoiced,
    coalesce((select sum(balance_due) from public.invoice_balances where status not in ('draft','void')), 0)::numeric(14, 2) as accounts_receivable,
    (coalesce((select sum(amount) from public.financial_transactions where transaction_type='income'), 0)
      + coalesce((select sum(least(total_amount, manual_paid_amount)) from public.invoices where status not in ('draft','void')), 0)
      - coalesce((select sum(amount) from public.financial_transactions where transaction_type='expense'), 0))::numeric(14, 2) as net_cash_flow
) base;

create or replace view public.monthly_cash_flow
with (security_invoker = true) as
select
  date_trunc('month', transaction_date)::date as month,
  coalesce(sum(amount) filter (where transaction_type = 'income'), 0)::numeric(14, 2) as income,
  coalesce(sum(amount) filter (where transaction_type = 'expense'), 0)::numeric(14, 2) as expenses,
  (coalesce(sum(amount) filter (where transaction_type = 'income'), 0)
    - coalesce(sum(amount) filter (where transaction_type = 'expense'), 0)
  )::numeric(14, 2) as net_cash_flow
from public.financial_transactions
group by date_trunc('month', transaction_date)::date;

