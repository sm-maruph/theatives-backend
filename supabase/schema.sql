create table if not exists public.invoice_payment_allocations (
  transaction_id bigint not null references public.financial_transactions(id) on delete cascade,
  invoice_id bigint not null references public.invoices(id) on delete cascade,
  allocated_amount numeric(14, 2) not null check (allocated_amount > 0),
  created_at timestamptz not null default now(),
  primary key (transaction_id, invoice_id)
);

-- Rebuild allocation records for one project. Every project-linked income
-- transaction is applied to that project's oldest non-draft/non-void invoices,
-- after each invoice's manual legacy payment value is accounted for.
create or replace function public.rebuild_project_invoice_allocations(p_project_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  payment record;
  invoice_row record;
  unallocated numeric(14, 2);
  invoice_balance numeric(14, 2);
  amount_to_allocate numeric(14, 2);
begin
  if p_project_id is null then
    return;
  end if;

  delete from public.invoice_payment_allocations a
  using public.financial_transactions t
  where a.transaction_id = t.id
    and t.project_id = p_project_id;

  for payment in
    select id, amount
    from public.financial_transactions
    where project_id = p_project_id
      and transaction_type = 'income'
    order by transaction_date, created_at, id
  loop
    unallocated := payment.amount;

    for invoice_row in
      select id, total_amount, manual_paid_amount
      from public.invoices
      where project_id = p_project_id
        and status not in ('draft', 'void')
      order by invoice_date, created_at, id
    loop
      exit when unallocated <= 0;

      select greatest(
        invoice_row.total_amount
        - least(invoice_row.total_amount, invoice_row.manual_paid_amount)
        - coalesce(sum(a.allocated_amount), 0),
        0
      )
      into invoice_balance
      from public.invoice_payment_allocations a
      where a.invoice_id = invoice_row.id;

      amount_to_allocate := least(unallocated, invoice_balance);
      if amount_to_allocate > 0 then
        insert into public.invoice_payment_allocations
          (transaction_id, invoice_id, allocated_amount)
        values
          (payment.id, invoice_row.id, amount_to_allocate);
        unallocated := unallocated - amount_to_allocate;
      end if;
    end loop;
  end loop;
end;
$$;

create or replace function public.refresh_invoice_allocations_from_transaction()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if new.project_id is not null then
      perform public.rebuild_project_invoice_allocations(new.project_id);
    end if;
    return new;
  elsif tg_op = 'DELETE' then
    delete from public.invoice_payment_allocations where transaction_id = old.id;
    if old.project_id is not null then
      perform public.rebuild_project_invoice_allocations(old.project_id);
    end if;
    return old;
  else
    -- Remove this payment's old allocations before rebuilding either project.
    delete from public.invoice_payment_allocations where transaction_id = new.id;
    if old.project_id is not null and old.project_id is distinct from new.project_id then
      perform public.rebuild_project_invoice_allocations(old.project_id);
    end if;
    if new.project_id is not null then
      perform public.rebuild_project_invoice_allocations(new.project_id);
    end if;
    return new;
  end if;
end;
$$;

create or replace function public.refresh_invoice_allocations_from_invoice()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'DELETE' then
    if old.project_id is not null then
      perform public.rebuild_project_invoice_allocations(old.project_id);
    end if;
    return old;
  elsif tg_op = 'UPDATE' then
    if old.project_id is not null and old.project_id is distinct from new.project_id then
      perform public.rebuild_project_invoice_allocations(old.project_id);
    end if;
    if new.project_id is not null then
      perform public.rebuild_project_invoice_allocations(new.project_id);
    end if;
    return new;
  else
    if new.project_id is not null then
      perform public.rebuild_project_invoice_allocations(new.project_id);
    end if;
    return new;
  end if;
end;
$$;

